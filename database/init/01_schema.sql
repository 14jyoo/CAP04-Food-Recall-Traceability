-- =====================================================================================================
-- Food Recall Traceability - PostgreSQL schema (AWS RDS). Matches the JPA entities exactly
-- (the app runs with ddl-auto=validate in the "postgres" profile).
--
-- KEY DESIGN
--   Natural keys (business identity, enforced UNIQUE)          Surrogate keys (graph references)
--   supplier        : canonical_code (SUP0001)                 supplier.id
--   supplier_alias  : alias_normalized  -> supplier            supplier_alias.id
--   supplier_lot    : (supplier_id, lot_code_normalized)       supplier_lot.id
--   internal_lot    : lot_code (plant-wide unique)             internal_lot.id
--   order_line      : (order_no, line_no)                      order_line.id
--   lineage_edge    : (parent_type, parent_id, child_type, child_id, source_record_id)
--
--   One polymorphic edge table carries every hop (receipt, consumption, split, merge, rework, dispatch),
--   so many-to-many consumption and split/merged batches are traversed by ONE recursive query.
--   The supplier's raw lot code is kept (lot_code_raw) for display/audit; lot_code_normalized is the key,
--   so "AB-7781", "ab 7781" and "AB7781" are the same lot.
-- =====================================================================================================

create table supplier (
    id              bigint generated by default as identity primary key,
    canonical_code  varchar(32)  not null unique,
    name            varchar(255) not null,
    country         varchar(255),
    contact_email   varchar(255)
);

create table supplier_alias (
    id               bigint generated by default as identity primary key,
    supplier_id      bigint       not null references supplier(id),
    alias_raw        varchar(255) not null,
    alias_normalized varchar(255) not null unique,
    resolution_type  varchar(16)  not null              -- AUTO | MANUAL (set by reconciliation)
);

create table supplier_lot (
    id                  bigint generated by default as identity primary key,
    supplier_id         bigint       not null references supplier(id),
    lot_code_raw        varchar(255) not null,
    lot_code_normalized varchar(255) not null,
    ingredient_code     varchar(255) not null,
    ingredient_name     varchar(255),
    quantity_received   numeric(18,3),
    uom                 varchar(255),
    received_date       date,
    expiry_date         date,
    source_system       varchar(255),
    source_record_id    varchar(255),
    unique (supplier_id, lot_code_normalized)
);

create table internal_lot (
    id               bigint generated by default as identity primary key,
    lot_code         varchar(255) not null unique,
    kind             varchar(16)  not null check (kind in ('INGREDIENT','WIP','FINISHED')),
    material_code    varchar(255),            -- ingredient code, or SKU for FINISHED
    material_name    varchar(255),
    quantity         numeric(18,3),
    uom              varchar(255),
    produced_date    date,
    production_line  varchar(255),
    source_system    varchar(255),
    source_record_id varchar(255)
);

create table order_line (
    id               bigint generated by default as identity primary key,
    order_no         varchar(255) not null,
    line_no          integer      not null,
    customer_code    varchar(255) not null,
    customer_name    varchar(255),
    customer_email   varchar(255),
    sku_code         varchar(255),
    quantity         numeric(18,3),
    uom              varchar(255),
    dispatch_date    date,
    ship_to_region   varchar(255),
    source_system    varchar(255),
    source_record_id varchar(255),
    unique (order_no, line_no)
);

create table lineage_edge (
    id               bigint generated by default as identity primary key,
    parent_type      varchar(16)  not null check (parent_type in ('SUPPLIER_LOT','INTERNAL_LOT','ORDER_LINE')),
    parent_id        bigint       not null,
    child_type       varchar(16)  not null check (child_type in ('SUPPLIER_LOT','INTERNAL_LOT','ORDER_LINE')),
    child_id         bigint       not null,
    edge_type        varchar(16)  not null check (edge_type in ('RECEIPT','CONSUMPTION','SPLIT','MERGE','REWORK','DISPATCH')),
    quantity         numeric(18,3),
    uom              varchar(255),
    event_time       timestamp(6),
    source_system    varchar(255),
    source_record_id varchar(255) not null,
    unique (parent_type, parent_id, child_type, child_id, source_record_id)
);
create index ix_edge_parent on lineage_edge (parent_type, parent_id);
create index ix_edge_child  on lineage_edge (child_type, child_id);

create table unmatched_record (
    id               bigint generated by default as identity primary key,
    source_system    varchar(255) not null,
    source_record_id varchar(255) not null,
    record_type      varchar(255) not null,
    issue            varchar(255) not null,
    offending_value  varchar(255),
    raw_row          varchar(4000),
    status           varchar(16)  not null check (status in ('OPEN','RESOLVED','IGNORED')),
    resolved_to      varchar(255),
    resolved_by      varchar(255),
    created_at       timestamp(6),
    resolved_at      timestamp(6)
);

create table recall_event (
    id                        bigint generated by default as identity primary key,
    reference                 varchar(255) not null,
    reason                    varchar(255) not null,
    severity                  varchar(255) not null,
    supplier_lot_id           bigint       not null references supplier_lot(id),
    status                    varchar(16)  not null check (status in ('SIMULATED','OPEN','NOTIFYING','CLOSED')),
    created_at                timestamp(6),
    lineage_computed_at       timestamp(6),
    all_notified_at           timestamp(6),
    closed_at                 timestamp(6),
    internal_lots_affected    integer not null,
    finished_batches_affected integer not null,
    order_lines_affected      integer not null,
    orders_affected           integer not null,
    customers_affected        integer not null,
    unresolved_references     integer not null,
    traversal_millis          bigint  not null,
    max_depth                 integer not null,
    completeness_verified     boolean not null,
    completeness_notes        varchar(4000)
);

create table recall_impact (
    id                bigint generated by default as identity primary key,
    recall_id         bigint not null references recall_event(id),
    order_line_id     bigint not null references order_line(id),
    finished_lot_code varchar(255),
    depth             integer not null,
    lineage_path      varchar(2000)
);
create index ix_impact_recall on recall_impact (recall_id);

create table notification (
    id                   bigint generated by default as identity primary key,
    recall_id            bigint       not null references recall_event(id),
    customer_code        varchar(255) not null,
    customer_name        varchar(255),
    customer_email       varchar(255),
    channel              varchar(255),
    order_lines_affected integer      not null,
    status               varchar(16)  not null check (status in ('PENDING','SENT','ACKNOWLEDGED','FAILED')),
    created_at           timestamp(6),
    sent_at              timestamp(6),
    acknowledged_at      timestamp(6),
    note                 varchar(1000)
);
create index ix_notif_recall on notification (recall_id);

create table ingestion_run (
    id                bigint generated by default as identity primary key,
    feed_type         varchar(255) not null,
    source_system     varchar(255) not null,
    file_name         varchar(255),
    started_at        timestamp(6),
    finished_at       timestamp(6),
    rows_read         integer not null,
    rows_accepted     integer not null,
    rows_rejected     integer not null,
    rows_unmatched    integer not null,
    rows_duplicate    integer not null,
    validation_report varchar(8000)
);
